"""
AgentState Definition for Agentic-DeepResearch.

Maintains the shared state across all LangGraph nodes:
Planner, Searcher, Writer, and Critic.
"""

from typing import TypedDict, List, Optional


class AgentState(TypedDict):
    question: str              # Original research query from the user
    language: str              # Detected query language: 'ar' (Arabic) or 'en' (English)
    sub_questions: List[str]   # Focused sub-queries generated by the Planner
    search_results: List[str]  # Grounded web search excerpts produced by the Searcher
    sources: List[str]         # Unique source URLs retrieved
    draft_answer: str          # Synthesis report produced by the Writer
    critique: str              # Evaluation critique produced by the Critic
    revision_count: int        # Number of revision iterations completed
    is_satisfactory: bool      # Critic verdict (True = PASS, False = FAIL)
    final_answer: str          # Final approved research report
